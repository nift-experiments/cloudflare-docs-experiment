#!/usr/bin/env python3
"""CP3 Cloudflare content-model census and strict compatibility gate.

Run against the frozen upstream checkout. This deliberately fails if it sees a
construct that is not present in compatibility.json; unknown MDX is never
silently flattened.
"""
from __future__ import annotations
import argparse, collections, json, re, sys
from pathlib import Path

TAG = re.compile(r'<([A-Z][A-Za-z0-9_.:-]*)\b')
IMPORT = re.compile(r'^\s*import\s+(.*?)\s+from\s+["\']([^"\']+)["\'];?', re.M|re.S)
FRONT = re.compile(r'^---\s*\n(.*?)\n---(?:\n|$)', re.S)
KEY = re.compile(r'^([A-Za-z_][\w-]*):(?:\s|$)', re.M)
EXPORT = re.compile(r'^\s*export\s+(?:const|let|var|function|class|default)\b', re.M)
EXPR = re.compile(r'(?<!\\)\{(?![\{#])')
DIRECTIVE = re.compile(r'(^|\n)\s*:::+\s*([A-Za-z][\w-]*)', re.M)
HTML_TAG = re.compile(r'<([a-z][a-z0-9-]*)\b')
FENCE = re.compile(r'^```\s*([^\s{]*)', re.M)

# Syntax intrinsic to MDX/Markdown, not a named imported component.
INTRINSIC = {"Fragment"}

def route_for(rel: str) -> str:
    x=rel.removeprefix('src/content/docs/')
    x=re.sub(r'\.(md|mdx)$','',x)
    x=re.sub(r'(^|/)index$','',x).strip('/')
    return '/' + (x+'/' if x else '')

def load_matrix(p: Path):
    d=json.loads(p.read_text())
    return d, set(d['components']), set(d['frontmatter']), set(d['directives'])

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('upstream',type=Path)
    ap.add_argument('--matrix',type=Path,default=Path('compatibility/content-model.json'))
    ap.add_argument('-o','--output',type=Path,default=Path('reports/CP3-CENSUS.json'))
    ap.add_argument('--fixtures',type=Path,default=Path('fixtures/cp3'))
    a=ap.parse_args(); root=a.upstream.resolve()
    docs=root/'src/content/docs'
    if not docs.is_dir(): raise SystemExit('expected src/content/docs in upstream checkout')
    matrix,known_components,known_front,known_directives=load_matrix(a.matrix)
    counts={k:collections.Counter() for k in ['components','frontmatter','imports','directives','html','fences']}
    examples={k:{} for k in ['components','frontmatter','directives']}; routes={}; unknown=[]
    files=sorted([*docs.rglob('*.md'),*docs.rglob('*.mdx')])
    for p in files:
        rel=p.relative_to(root).as_posix(); s=p.read_text(errors='replace'); route=route_for(rel)
        if route in routes: unknown.append({'kind':'route-collision','value':route,'files':[routes[route],rel]})
        routes[route]=rel
        fm=FRONT.match(s)
        for key in KEY.findall(fm.group(1) if fm else ''):
            counts['frontmatter'][key]+=1; examples['frontmatter'].setdefault(key,rel)
            if key not in known_front: unknown.append({'kind':'frontmatter','value':key,'file':rel})
        for c in TAG.findall(s):
            if c in INTRINSIC: continue
            counts['components'][c]+=1; examples['components'].setdefault(c,rel)
            if c not in known_components: unknown.append({'kind':'component','value':c,'file':rel})
        for _,src in IMPORT.findall(s): counts['imports'][src]+=1
        for _,d in DIRECTIVE.findall(s):
            counts['directives'][d]+=1; examples['directives'].setdefault(d,rel)
            if d not in known_directives: unknown.append({'kind':'directive','value':d,'file':rel})
        counts['html'].update(HTML_TAG.findall(s)); counts['fences'].update(x or '(plain)' for x in FENCE.findall(s))
        if EXPORT.search(s): counts.setdefault('features',collections.Counter())['mdx-export']+=1
        if EXPR.search(s): counts.setdefault('features',collections.Counter())['jsx-expression']+=1
    report={'schema':1,'pinned_upstream':matrix['pinned_upstream'],'docs':len(files),'routes':len(routes),'route_sample':dict(list(sorted(routes.items()))[:20]),'counts':{k:v.most_common() for k,v in counts.items()},'examples':examples,'unknown_count':len(unknown),'unknown':unknown[:5000]}
    a.output.parent.mkdir(parents=True,exist_ok=True); a.output.write_text(json.dumps(report,indent=2)+'\n')
    a.fixtures.mkdir(parents=True,exist_ok=True)
    (a.fixtures/'README.md').write_text('# CP3 real-usage fixture index\n\nGenerated by `tools/content_model.py` from the frozen upstream checkout.\n\n'+''.join(f'- `{k}` — `{v}`\n' for k,v in sorted(examples['components'].items())))
    print(f"scanned {len(files)} docs / {len(routes)} routes; unknown={len(unknown)}")
    if unknown:
        print('STRICT GATE FAILED: compatibility matrix has unknown constructs',file=sys.stderr); return 2
    print('STRICT GATE PASSED: every discovered named construct is classified'); return 0
if __name__=='__main__': raise SystemExit(main())
